def format_fragment(number: int, text: str, page_from: int | None, page_to: int | None, section: str | None) -> str:
    meta = []
    if page_from is not None:
        meta.append(f"стр. {page_from}" if page_to in (None, page_from) else f"стр. {page_from}–{page_to}")
    if section:
        meta.append(f"раздел «{section}»")
    header = f"[{number}]" + (f" ({', '.join(meta)})" if meta else "")
    return f"{header}\n{text}"
