def main() -> None:
    html = ["<h2 style='text-align:center'>ДОГОВОР ПОСТАВКИ № 47/2025</h2>"]
    html.append("<p style='text-align:center'>г. Санкт-Петербург, 10 января 2025 г.</p>")
    for title, clauses in SECTIONS:
        html.append(f"<p><b>{title}</b></p>")
        html.extend(f"<p>{clause}</p>" for clause in clauses)
        html.append("<p>&nbsp;</p>" * 6)

    story = pymupdf.Story(html="".join(html), user_css="p { font-size: 12pt; line-height: 1.5 }")
    writer = pymupdf.DocumentWriter(str(OUT))
    rect = pymupdf.paper_rect("a4")
    content = pymupdf.Rect(rect.x0 + 72, rect.y0 + 72, rect.x1 - 72, rect.y1 - 72)
    more = True
    while more:
        device = writer.begin_page(rect)
        more, _ = story.place(content)
        story.draw(device)
        writer.end_page()
    writer.close()
    print(f"{OUT} ({pymupdf.open(OUT).page_count} стр.)")  # noqa: T201


if __name__ == "__main__":
    main()
